#!/usr/bin/env python3
"""Build the generated C poem library from assets/poems/poem_library.json.

The JSON is the single source of truth for 光之诗库. Each batch can be extended
without touching C code; this tool validates the data and emits
main/assets/poem_library.c/h.

Usage:
    python3 tools/build_poem_library.py
    python3 tools/build_poem_library.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "poems" / "poem_library.json"
HEADER = ROOT / "main" / "assets" / "poem_library.h"
IMPL = ROOT / "main" / "assets" / "poem_library.c"

MAX_LINES = 12
MAX_LINE_CHARS = 12
MIN_GRADE = 1
MAX_GRADE = 6


def fail(message: str) -> None:
    raise SystemExit(f"ERROR: {message}")


def char_count(text: str) -> int:
    return len(text)


def load_source() -> dict:
    if not SOURCE.is_file():
        fail(f"missing {SOURCE}")
    try:
        data = json.loads(SOURCE.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        fail(f"{SOURCE} is not valid JSON: {exc}")
    return data


def validate(data: dict) -> tuple[list[dict], list[dict]]:
    if data.get("schema_version") != 1:
        fail("schema_version must be 1")
    name = data.get("name")
    if not isinstance(name, str) or not name:
        fail("name is required")
    if not isinstance(data.get("total_target"), int) or data["total_target"] <= 0:
        fail("total_target must be a positive integer")

    batches = data.get("batches")
    if not isinstance(batches, list) or not batches:
        fail("batches must be a non-empty list")
    batch_ids: list[str] = []
    for batch in batches:
        for key in ("id", "name", "description"):
            if not isinstance(batch.get(key), str) or not batch[key]:
                fail(f"batch field {key} is required")
        if not isinstance(batch.get("target_count"), int) or batch["target_count"] <= 0:
            fail(f"batch {batch['id']} needs a positive target_count")
        if batch["id"] in batch_ids:
            fail(f"duplicate batch id {batch['id']}")
        batch_ids.append(batch["id"])

    poems = data.get("poems")
    if not isinstance(poems, list) or not poems:
        fail("poems must be a non-empty list")

    seen_ids: set[int] = set()
    seen_titles: set[tuple[str, str, str]] = set()
    for poem in poems:
        pid = poem.get("id")
        if not isinstance(pid, int) or pid <= 0:
            fail(f"poem id must be a positive integer: {poem!r}")
        if pid in seen_ids:
            fail(f"duplicate poem id {pid}")
        seen_ids.add(pid)

        for key in ("title", "author", "dynasty", "batch"):
            if not isinstance(poem.get(key), str) or not poem[key]:
                fail(f"poem {pid} field {key} is required")
        if poem["batch"] not in batch_ids:
            fail(f"poem {pid} uses unknown batch {poem['batch']}")

        grade = poem.get("grade")
        if not isinstance(grade, int) or not MIN_GRADE <= grade <= MAX_GRADE:
            fail(f"poem {pid} grade must be {MIN_GRADE}..{MAX_GRADE}")

        tags = poem.get("tags")
        if not isinstance(tags, list) or not tags or not all(
            isinstance(tag, str) and tag for tag in tags
        ):
            fail(f"poem {pid} needs at least one tag")

        lines = poem.get("lines")
        if not isinstance(lines, list) or not 2 <= len(lines) <= MAX_LINES:
            fail(f"poem {pid} must have 2..{MAX_LINES} lines")
        for line in lines:
            if not isinstance(line, str) or not line:
                fail(f"poem {pid} has an empty line")
            if char_count(line) > MAX_LINE_CHARS:
                fail(
                    f"poem {pid} line {line!r} has {char_count(line)} chars, "
                    f"limit is {MAX_LINE_CHARS}"
                )

        key = (poem["title"], poem["author"], lines[0])
        if key in seen_titles:
            fail(f"duplicate poem title/author/first-line {key}")
        seen_titles.add(key)

    return poems, batches


def c_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def render_header(data: dict, batches: list[dict]) -> str:
    return f"""// Generated by tools/build_poem_library.py. Do not edit by hand.
#pragma once

#include <stdint.h>

#define POEM_MAX_LINES {MAX_LINES}

typedef struct {{
    uint16_t id;
    const char *title;
    const char *author;
    const char *dynasty;
    const char *tags;
    const char *const *lines;
    uint8_t line_count;
    uint8_t grade;
    uint8_t batch;
}} poem_t;

const char *poem_library_name(void);
uint16_t poem_library_count(void);
uint16_t poem_library_total_target(void);
const poem_t *poem_library_at(uint16_t index);
uint8_t poem_library_batch_count(void);
const char *poem_library_batch_name(uint8_t batch);
const char *poem_library_batch_desc(uint8_t batch);
"""


def render_impl(data: dict, poems: list[dict], batches: list[dict]) -> str:
    batch_index = {batch["id"]: i for i, batch in enumerate(batches)}
    out: list[str] = []
    out.append("// Generated by tools/build_poem_library.py. Do not edit by hand.")
    out.append('#include "poem_library.h"')
    out.append("")
    out.append("static const char *const BATCH_NAMES[] = {")
    for batch in batches:
        out.append(f"    {c_string(batch['name'])},")
    out.append("};")
    out.append("")
    out.append("static const char *const BATCH_DESCS[] = {")
    for batch in batches:
        out.append(f"    {c_string(batch['description'])},")
    out.append("};")
    out.append("")

    for poem in poems:
        pid = poem["id"]
        out.append(
            f"static const char *const LINES_{pid}[POEM_MAX_LINES] = {{"
        )
        for line in poem["lines"]:
            out.append(f"    {c_string(line)},")
        out.append("};")
    out.append("")
    out.append("static const poem_t POEMS[] = {")
    for poem in poems:
        pid = poem["id"]
        out.append("    {")
        out.append(f"        .id = {pid},")
        out.append(f"        .title = {c_string(poem['title'])},")
        out.append(f"        .author = {c_string(poem['author'])},")
        out.append(f"        .dynasty = {c_string(poem['dynasty'])},")
        out.append(f"        .tags = {c_string(' '.join(poem['tags']))},")
        out.append(f"        .lines = LINES_{pid},")
        out.append(f"        .line_count = {len(poem['lines'])},")
        out.append(f"        .grade = {poem['grade']},")
        out.append(f"        .batch = {batch_index[poem['batch']]},")
        out.append("    },")
    out.append("};")
    out.append("")
    out.append(f"#define POEM_COUNT {len(poems)}")
    out.append(f"#define POEM_BATCH_COUNT {len(batches)}")
    out.append("")
    out.append("const char *poem_library_name(void)")
    out.append("{")
    out.append(f"    return {c_string(data['name'])};")
    out.append("}")
    out.append("")
    out.append("uint16_t poem_library_count(void)")
    out.append("{")
    out.append("    return POEM_COUNT;")
    out.append("}")
    out.append("")
    out.append("uint16_t poem_library_total_target(void)")
    out.append("{")
    out.append(f"    return {data['total_target']}u;")
    out.append("}")
    out.append("")
    out.append("const poem_t *poem_library_at(uint16_t index)")
    out.append("{")
    out.append("    if (index >= POEM_COUNT) {")
    out.append("        index = 0;")
    out.append("    }")
    out.append("    return &POEMS[index];")
    out.append("}")
    out.append("")
    out.append("uint8_t poem_library_batch_count(void)")
    out.append("{")
    out.append("    return POEM_BATCH_COUNT;")
    out.append("}")
    out.append("")
    out.append("const char *poem_library_batch_name(uint8_t batch)")
    out.append("{")
    out.append("    if (batch >= POEM_BATCH_COUNT) {")
    out.append("        batch = 0;")
    out.append("    }")
    out.append("    return BATCH_NAMES[batch];")
    out.append("}")
    out.append("")
    out.append("const char *poem_library_batch_desc(uint8_t batch)")
    out.append("{")
    out.append("    if (batch >= POEM_BATCH_COUNT) {")
    out.append("        batch = 0;")
    out.append("    }")
    out.append("    return BATCH_DESCS[batch];")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the generated files are out of date instead of writing",
    )
    args = parser.parse_args()

    data = load_source()
    poems, batches = validate(data)
    header = render_header(data, batches)
    impl = render_impl(data, poems, batches)

    if args.check:
        problems = []
        for path, expected in ((HEADER, header), (IMPL, impl)):
            if not path.is_file():
                problems.append(f"missing generated file {path}")
            elif path.read_text(encoding="utf-8") != expected:
                problems.append(f"{path} is out of date; rerun tools/build_poem_library.py")
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            return 1
        print(
            f"Poem library: PASS ({len(poems)} poems, "
            f"{sum(1 for p in poems if p['grade'] <= 3)} core, "
            f"{sum(1 for p in poems if p['grade'] >= 4)} expansion)"
        )
        return 0

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header, encoding="utf-8", newline="\n")
    IMPL.parent.mkdir(parents=True, exist_ok=True)
    IMPL.write_text(impl, encoding="utf-8", newline="\n")
    print(
        f"Generated {HEADER.relative_to(ROOT)} and {IMPL.relative_to(ROOT)} "
        f"({len(poems)} poems)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
